import * as React from "react"
import { cn } from "@/lib/utils"
import { Select as SelectPrimitive } from "radix-ui"

import { Check, ChevronDown, ChevronUp } from "lucide-react"

/**
 * 下拉菜单，替代原生 `<select>`（见 AGENTS.md 不变量 7）。
 *
 * 取自 shadcn registry，但按本项目环境改了四处——
 * **重新从 registry 拉取会把这些改动冲掉，务必逐条比对**：
 * 1. `SelectContent` 的 `data-open:` / `data-closed:` 改为标准 `data-[state=…]`。
 *    Radix 渲染的是 `data-state="open"`，原写法生成不出任何 CSS，展开收起动画完全不生效。
 *    与 `switch.tsx`、`tooltip.tsx` 踩过的是同一个坑，`tsc` 和 `oxlint` 都发现不了。
 * 2. `position` 默认改为 `popper`、`align` 改为 `start`——
 *    registry 的 `item-aligned` 会让面板盖在触发器上，不像下拉菜单。
 * 3. 去掉硬性 `min-w-36`，改为 `min-w-(--radix-select-trigger-width)` 跟随触发器宽度。
 * 4. 图标从不存在的 `@/app/(create)/components/icon-placeholder` 换成 `lucide-react`。
 */

function Select({
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Root>) {
  return <SelectPrimitive.Root data-slot="select" {...props} />
}

function SelectGroup({
  className,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Group>) {
  return (
    <SelectPrimitive.Group
      data-slot="select-group"
      className={cn("scroll-my-1 p-1", className)}
      {...props}
    />
  )
}

function SelectValue({
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Value>) {
  return <SelectPrimitive.Value data-slot="select-value" {...props} />
}

function SelectTrigger({
  className,
  size = "default",
  children,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Trigger> & {
  size?: "sm" | "default"
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        "flex w-fit items-center justify-between gap-1.5 rounded-lg border border-input bg-transparent py-2 pr-2 pl-2.5 text-sm whitespace-nowrap transition-colors outline-none select-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50 disabled:cursor-not-allowed disabled:opacity-50 aria-invalid:border-destructive aria-invalid:ring-3 aria-invalid:ring-destructive/20 data-placeholder:text-muted-foreground data-[size=default]:h-8 data-[size=sm]:h-7 data-[size=sm]:rounded-[min(var(--radius-md),10px)] *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-1.5 dark:bg-input/30 dark:hover:bg-input/50 dark:aria-invalid:border-destructive/50 dark:aria-invalid:ring-destructive/40 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon asChild>
        <ChevronDown
          className="pointer-events-none size-4 text-muted-foreground"
        />
      </SelectPrimitive.Icon>
    </SelectPrimitive.Trigger>
  )
}

/**
 * 下拉面板。
 *
 * 与 registry 原版的两处差异（勿改回去）：
 * 1. `position` 默认改为 `popper`——原版的 `item-aligned` 会把面板**盖在触发器上**
 *    （对齐当前选中项），观感上不像下拉菜单。`popper` 才是真正的「从下方展开」。
 * 2. 去掉 `min-w-36`（144px），改为跟随触发器宽度：原版硬性最小宽度会让面板
 *    比触发器还宽，窄触发器上尤其突兀。
 */
function SelectContent({
  className,
  children,
  position = "popper",
  align = "start",
  sideOffset = 4,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content>) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        className={cn(
          "relative z-50 max-h-(--radix-select-content-available-height) origin-(--radix-select-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover text-popover-foreground shadow-md ring-1 ring-foreground/10 duration-100 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-[state=open]:animate-in data-[state=open]:fade-in-0 data-[state=open]:zoom-in-95 data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=closed]:zoom-out-95",
          // 宽度跟随触发器，不再强制 min-w-36
          "min-w-(--radix-select-trigger-width)",
          className
        )}
        position={position}
        align={align}
        sideOffset={sideOffset}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport className="w-full p-1">
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
}

